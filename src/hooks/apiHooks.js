import {useState, useEffect} from 'react';
import {fetchData} from '../utils/fetchData';

const MEDIA_API = import.meta.env.VITE_MEDIA_API;
const AUTH_API = import.meta.env.VITE_AUTH_API;
const UPLOAD_API = import.meta.env.VITE_UPLOAD_SERVER;

const useMedia = () => {
  const [mediaArray, setMediaArray] = useState([]);
  useEffect(() => {
    const getMedia = async (limit) => {
      // Fetch media files from the API
      const mediafiles = await fetchData(MEDIA_API + '/media?limit=' + limit);
      // Fetch user data for each media file and add the username to the media file object
      const updatedMediafiles = await Promise.all(
        mediafiles.map(async (mediafile) => {
          const userdata = await fetchData(
            `${AUTH_API}/users/${mediafile.user_id}`,
          );
          return {...mediafile, username: userdata.username};
        }),
      );

      setMediaArray(updatedMediafiles);
    };
    getMedia(10);
  }, []);

  const postMedia = async (file, inputs, token) => {
    // TODO: create a suitable object for Media API: without media_id, user_id, thumbnail and created_at. All those are generated by the API. See the media API documentation.
    const mediaData = {
      title: inputs.title,
      description: inputs.description,
      filename: file.filename,
      media_type: file.media_type,
      filesize: file.filesize,
    };
    // TODO: post the data to Media API and get the data as MediaResponse
    const fetchOptions = {
      method: 'POST',
      headers: {
        'Content-Type': 'application/json',
        Authorization: 'Bearer ' + token,
      },
      body: JSON.stringify(mediaData),
    };
    const mediaResponse = await fetchData(MEDIA_API + '/media', fetchOptions);
    console.log('Media Response', mediaResponse);

    // TODO: return the data
    return mediaResponse;
  };

  return {mediaArray, postMedia};
};

const useUser = () => {
  const getUserInfo = async (userId) => {
    const userData = await fetchData(`${AUTH_API}/users/${userId}`);
    return userData;
  };

  const getUserByToken = async (token) => {
    const result = await fetchData(`${AUTH_API}/users/token`, {
      headers: {Authorization: `Bearer ${token}`},
    });
    return result.user;
  };

  return {getUserInfo, getUserByToken};
};

const useAuthentication = () => {
  const postLogin = async (inputs) => {
    const fetchOptions = {
      method: 'POST',
      headers: {
        'Content-Type': 'application/json',
      },
      body: JSON.stringify(inputs),
    };
    const loginResult = await fetchData(
      import.meta.env.VITE_AUTH_API + '/auth/login',
      fetchOptions,
    );
    return loginResult;
  };

  return postLogin;
};

const useRegistration = () => {
  const postRegisteration = async (inputs) => {
    const fetchOptions = {
      method: 'POST',
      headers: {
        'Content-Type': 'application/json',
      },
      body: JSON.stringify(inputs),
    };
    return await fetchData(`${AUTH_API}/users`, fetchOptions);
  };

  return postRegisteration;
};

